const assert=require('node:assert/strict');
const {isDeepStrictEqual}=require('node:util');
globalThis.SECRET_DEFINITIONS=require('../definition-workflow.js');
globalThis.SECRET_MEANING_REQUESTS=require('../meaning-requests.js');
globalThis.SECRET_COOPERATIVE_REFRESH=require('../cooperative-refresh.js');
const api=require('../word-relationships.js');
if(!globalThis.crypto)globalThis.crypto=require('node:crypto').webcrypto;
const key=row=>`${row.rowId}|${row.timestamp}`;
async function run(){
  const database=new Map();let failLinks=false,failDelete=false;
  const client={
    scan:()=>({promise:async()=>({Items:structuredClone([...database.values()])})}),
    get:({Key})=>({promise:async()=>({Item:structuredClone(database.get(key(Key)))})}),
    put:params=>({promise:async()=>{
      if(failLinks&&params.Item.relationshipData)throw new Error('Link offline');
      const prior=database.get(key(params.Item));
      const field=params.ExpressionAttributeNames?.['#data'];
      if(params.ConditionExpression==='attribute_not_exists(rowId)'&&prior || field&&!isDeepStrictEqual(prior?.[field],params.ExpressionAttributeValues[':data']))throw Object.assign(new Error('Concurrent change'),{code:'ConditionalCheckFailedException'});
      database.set(key(params.Item),structuredClone(params.Item));
    }}),
    delete:params=>({promise:async()=>{if(failDelete)throw new Error('Delete offline');const field=params.ExpressionAttributeNames['#data'];
      assert.deepEqual(database.get(key(params.Key))[field],params.ExpressionAttributeValues[':data']);database.delete(key(params.Key));}})
  };
  const service=api.create({client:()=>client,table:'secretWords',user:()=> 'alice'});
  const root=await service.saveInventory({kind:'root',spelling:'ka',pronunciation:'ka',meaning:'fire',notes:'old root'});
  const prefix=await service.saveInventory({kind:'prefix',spelling:'ne',pronunciation:'ne',meaning:'not'});
  assert.equal(service.inventory().length,2);assert.equal(service.resolve(root.rowId).category,'root-only');
  const bob=api.create({client:()=>client,table:'secretWords',user:()=> 'bob'});bob.load(await bob.read());
  const edited=await bob.saveInventory({...root.morphemeData,notes:'shared editing'},root);
  assert.equal(edited.morphemeData.author,'alice');assert.equal(edited.morphemeData.editedBy,'bob');
  await assert.rejects(service.saveInventory({...root.morphemeData,notes:'stale'},root),/changed/);
  service.load(await service.read());
  const saved=await service.saveWord({word:'kan',pronunciation:'kan',meaning:'flame',operationId:'one'});
  assert.equal(saved.hearted,true);assert.equal(saved.definitionReview.status,'candidate');
  assert.ok(saved.timestamp>0,'Dictionary words need positive stable timestamps, unlike metadata rows');
  const undefinedWord=await service.saveWord({word:'kam',pronunciation:'kam',operationId:'two'});
  assert.equal(SECRET_DEFINITIONS.classification(undefinedWord),'undefined');
  const id=await service.ensureWord('kan'),other=await service.ensureWord('kam');
  assert.equal(await service.ensureWord('kan'),id,'Stable word identities are reused');
  const derived=await service.link(id,root.rowId,'derived','a fiery thing',1);
  assert.equal(service.relationships(id)[0].label,'Derived from');
  assert.equal(service.relationships(root.rowId)[0].label,'Derived words');
  assert.equal((await service.link(id,root.rowId,'derived')).rowId,derived.rowId,'Retries are idempotent');
  await assert.rejects(service.link(id,root.rowId,'derived','',0,null,false),/already exists/,'Interactive duplicate links are rejected');
  const variant=await service.link(id,other,'variant');
  assert.equal((await service.link(other,id,'variant')).rowId,variant.rowId,'Symmetric duplicates have one key');
  assert.equal(service.relationships(other)[0].label,'Variant of');
  await assert.rejects(service.link(id,id,'derived'),/different/);
  await assert.rejects(service.link(id,other,'made-up'),/type/);
  const compound=await service.link(id,prefix.rowId,'compound','part',0);
  assert.deepEqual(service.relationships(id).map(edge=>edge.data.type),['variant','compound','derived']);
  const revised=await service.link(id,root.rowId,'derived','expanded explanation',1,derived);
  assert.equal(revised.relationshipData.author,'alice');
  await assert.rejects(service.link(id,root.rowId,'derived','stale',1,derived),/changed/);
  const relabeled=await service.link(id,root.rowId,'related','expanded explanation',1,revised);
  assert.equal(service.relationships(root.rowId).find(edge=>edge.target.id===id).label,'Related to');
  assert.equal(database.has(key(revised)),false,'Editing the type removes the old keyed relationship');
  await service.link(id,root.rowId,'derived','expanded explanation',1,relabeled);
  const promoted=await service.promote(edited);
  assert.equal(service.resolve(root.rowId).category,'candidate');
  const promotion=service.inventory().find(item=>item.rowId===root.rowId);
  assert.equal(promotion.morphemeData.spelling,'ka');assert.equal(promotion.morphemeData.author,'alice');
  database.set(key(saved),{...saved,word:'ken'});service.load(await service.read());await service.renameWord('kan','ken');
  assert.equal(service.resolve(id).spelling,'ken');assert.equal(service.relationships(root.rowId)[0].target.spelling,'ken');
  database.set(key(promoted),{...promoted,word:'ki'});service.load(await service.read());await service.renameWord('ka','ki');
  assert.equal(service.resolve(root.rowId).spelling,'ki','Promoted inventory follows counterpart renames');
  database.set(key(saved),{...saved,word:'ken',meaning:null});service.load(await service.read());
  assert.equal(service.relationships(id).length,3,'Undefine retains relationships');
  failLinks=true;
  await assert.rejects(service.link(other,prefix.rowId,'prefix'),/offline/);
  assert.ok(database.get(key(undefinedWord)).hearted,'A failed link never rolls back a saved word');failLinks=false;
  await service.link(other,prefix.rowId,'prefix');await service.link(other,prefix.rowId,'prefix');
  assert.equal(service.relationships(other).filter(edge=>edge.data.type==='prefix').length,1);
  failDelete=true;await assert.rejects(service.removeInventory(prefix),/offline/);failDelete=false;
  assert.ok(service.resolve(prefix.rowId),'Failed deletion leaves entry visible for retry');
  await service.removeInventory(prefix);assert.equal(service.resolve(prefix.rowId),null);assert.ok(service.resolve(other));
  assert.ok(database.get(key(undefinedWord)).hearted);
  await service.removeWord('ken');assert.equal(service.resolve(id),null);assert.equal(service.relationships(root.rowId).length,0);
  assert.ok(service.resolve(root.rowId),'Deleting a word does not delete its root');
  const accepted={rowId:'bob::old',timestamp:1,word:'old',pronunciation:'o',meaning:'old meaning',user:'bob',hearted:true,definitionReview:{status:'defined'},meaningUpdatedTimestamp:1};
  database.set(key(accepted),accepted);
  await assert.rejects(service.saveWord({word:'old',pronunciation:'o',meaning:'replace'}),/already exists/);
  const used=await service.saveWord({word:'old',pronunciation:'bad',meaning:'replace',useExisting:true,operationId:'existing'});
  assert.equal(used.meaning,null);assert.equal(used.pronunciation,'o');assert.deepEqual(database.get(key(accepted)),accepted);
  const request=await service.requests.add('inside');
  const assigned=await service.saveWord({word:'inn',pronunciation:'in',request});
  assert.equal(assigned.meaning,'inside');assert.equal(assigned.conceptData.author,'alice');assert.equal(assigned.hearted,true);
  assert.equal(assigned.definitionReview.status,'candidate');
  const emptyRoot=await service.saveInventory({kind:'root',spelling:'zu',pronunciation:'zu'});
  await assert.rejects(service.promote(emptyRoot),/Enter a definition/);
  assert.equal((await service.promote(emptyRoot,'inner')).meaning,'inner','Root promotion accepts an explicitly supplied missing meaning');
  assert.equal(api.assemble([{spelling:'ne-'},{spelling:'k.a'},{spelling:'n'}]),'nekan');
  const report=api.preview('neka','manual',{}, {derivePronunciationFromSpelling:()=>({pronunciation:'',warnings:['Missing mapping']}),analyzeEntryAgainstRuleConfig:()=>({available:false,warnings:[]})});
  assert.deepEqual(report.warnings,['Missing mapping','The active rules cannot verify this word.']);
  const metadata=(await service.read()).filter(row=>row.morphemeData||row.lexemeData||row.relationshipData);
  assert.equal(SECRET_MEANING_REQUESTS.groupWords(metadata).length,0,'Metadata is not a dictionary word');
  assert.equal(require('../symbol-analytics.js').analyze(metadata,{vowels:[{symbol:'a'}],consonants:[{symbol:'k'}]}).selected,0,'Metadata is excluded from analytics');
  console.log('Word relationship service and assembly tests passed.');
}
run().catch(error=>{console.error(error);process.exitCode=1;});
